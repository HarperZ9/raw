"""Write the reference runtime's address table (1.6.1170), where RAW's addresses were measured. Original work, MIT.

    python -I tools/enginemap/reference_table.py --exe <SkyrimSE.exe 1.6.1170> --refs <engine_rt_refs.tsv>
        --entries data/versions/entries.tsv --version 1.6.1170.0 --out data/versions/skyrimse-1.6.1170.tsv

engine_rt_refs.tsv (rt_inputs.py, from the engine map) gives the settings and globals; entries.tsv gives every other
address RAW uses, with its 1.6.1170 value in the ref column. The exe supplies only its time stamp and image size.
"""
from __future__ import annotations

import argparse
import csv
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pe_image  # noqa: E402


def rows(path):
    with open(path, encoding="utf-8") as f:
        yield from csv.DictReader((l for l in f if not l.startswith("#")), delimiter="\t")


def main():
    ap = argparse.ArgumentParser()
    for k in ("exe", "refs", "entries", "version", "out"):
        ap.add_argument("--" + k, required=True)
    a = ap.parse_args()
    pe = pe_image.Image(a.exe).pe
    out = []
    for r in rows(a.refs):
        out.append((r["name"], r["kind"], r["rva"], "measured" if r["kind"] == "setting" else "addrlib",
                    "engine map (settings scan)" if r["kind"] == "setting" else "engine map (Address Library ids)"))
    for e in rows(a.entries):
        if e["rule"].startswith("given"):
            out.append((e["name"], e["kind"], e["ref"], "commonlib", "CommonLibSSE-NG layout notes, not yet used by RAW"))
        else:
            out.append((e["name"], e["kind"], e["ref"], "measured", "used in game on 1.6.1170 (engine control 1 to 7)"))
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# RAW address table for SkyrimSE.exe {a.version}, the reference runtime. Generated by\n"
                "# tools/enginemap/reference_table.py; addresses and names only.\n")
        f.write(f"version\t{a.version}\ntimestamp\t0x{pe.FILE_HEADER.TimeDateStamp:08X}\n"
                f"size_of_image\t0x{pe.OPTIONAL_HEADER.SizeOfImage:X}\n")
        f.write("name\tkind\tvalue\tconfidence\tsource\n")
        for row in out:
            f.write("\t".join(row) + "\n")
    print(f"{a.out}: {len(out)} rows")


if __name__ == "__main__":
    main()
